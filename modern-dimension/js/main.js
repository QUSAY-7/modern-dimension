let currentLang = 'ar';

// دالة تبديل اللغة الفوري بين العربي والإنجليزي
function toggleLanguage() {
  currentLang = currentLang === 'ar' ? 'en' : 'ar';
  document.documentElement.lang = currentLang;
  document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';

  if (currentLang === 'en') {
    document.body.classList.add('en-lang');
  } else {
    document.body.classList.remove('en-lang');
  }

  // تحديث نصوص الصفحة
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[currentLang][key]) {
      el.textContent = translations[currentLang][key];
    }
  });

  // تحديث نص زر اللغة
  const langText = document.getElementById('langText');
  if (langText) {
    langText.textContent = translations[currentLang].lang_btn;
  }
}

// دالة فلترة المشاريع
function filterProjects(category) {
  const cards = document.querySelectorAll('.project-card');
  const buttons = document.querySelectorAll('.filter-btn');

  buttons.forEach(btn => btn.classList.remove('active'));
  event.target.classList.add('active');

  cards.forEach(card => {
    if (category === 'all' || card.getAttribute('data-category') === category) {
      card.style.display = 'block';
    } else {
      card.style.display = 'none';
    }
  });
}

// فتح وإغلاق القائمة في الهواتف
function toggleMobileMenu() {
  const menu = document.getElementById('navMenu');
  if (menu.style.display === 'flex') {
    menu.style.display = 'none';
  } else {
    menu.style.display = 'flex';
    menu.style.flexDirection = 'column';
    menu.style.position = 'absolute';
    menu.style.top = '80px';
    menu.style.left = '0';
    menu.style.right = '0';
    menu.style.background = '#fff';
    menu.style.padding = '20px';
    menu.style.boxShadow = '0 10px 20px rgba(0,0,0,0.1)';
  }
}

